    | 只在 `keys` 里没有登记当前 key_id 时作为补充。
    */
    'secret' => env('CRYPTO_SECRET'),

    /*
    |--------------------------------------------------------------------------
    | 多密钥并存（为轮换预留）
    |--------------------------------------------------------------------------
    | 形如 ['k1' => '旧密钥', 'k2' => '新密钥']。
    | 轮换流程见 App\Modules\Crypto\KeyRing 的文件注释。
    | 一期留空即可 —— 单靠上面的 key_id + secret 就能跑。
    */
    'keys' => [],

];
