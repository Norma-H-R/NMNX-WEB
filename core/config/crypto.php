<?php

declare(strict_types=1);

/**
 * 加密模块配置
 *
 * 对应文档：docs/modules/06-crypto.md
 * 一期状态：只留接口，不实现算法（CRYPTO_DRIVER=null，原样透传）。
 *
 * ⚠️ `key_id` 一期就要写进配置，即使只有一把密钥 ——
 *    密钥标识一旦随协议发出去就改不动了（见 requirements.md 的 B-5）。
 */

return [

    /*
    |--------------------------------------------------------------------------
    | 驱动
    |--------------------------------------------------------------------------
    | 目前只支持 `null`（原样透传，不做加解密）。
